#!/usr/bin/env python3
"""Copies the shared build settings of MeshCore into meshcore_base.ini.

Our platformio.ini builds MeshCore from the meshcore/ submodule. MeshCore's own platformio.ini
cannot be included as is (it pulls the 100+ variants of the official repo), so the few sections
we build on ([arduino_base], [esp32_base], [sensor_base]) are copied from it, with the paths
adapted to our layout (meshcore/ is a sub-folder here).

    python3 tools/sync_meshcore_base.py           # rewrite meshcore_base.ini
    python3 tools/sync_meshcore_base.py --check   # exit 1 if it is out of date (CI, update workflow)

Run it after every MeshCore version change.
"""
import configparser
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "meshcore", "platformio.ini")
OUT = os.path.join(ROOT, "meshcore_base.ini")
SECTIONS = ["arduino_base", "esp32_base", "sensor_base"]

# Paths of MeshCore's platformio.ini are relative to its own folder.
REWRITE = {
    "extra_scripts": lambda v: " ".join("meshcore/" + p if not p.startswith(("/", "pre:", "post:")) else p
                                         for p in v.split()),
}


def submodule_version():
    head = os.path.join(ROOT, "meshcore")
    try:
        import subprocess
        return subprocess.check_output(["git", "-C", head, "describe", "--tags", "--always"], text=True).strip()
    except Exception:
        return "?"


def generate():
    if not os.path.exists(SRC):
        sys.exit("meshcore/platformio.ini not found: run  git submodule update --init")
    cp = configparser.RawConfigParser(strict=False, delimiters=("=",), comment_prefixes=(";", "#"),
                                      inline_comment_prefixes=(";",))
    cp.optionxform = str
    cp.read(SRC)
    lines = [
        "; GENERATED by tools/sync_meshcore_base.py from meshcore/platformio.ini - do not edit.",
        f"; MeshCore version: {submodule_version()}",
        "",
    ]
    for sec in SECTIONS:
        if not cp.has_section(sec):
            sys.exit(f"section [{sec}] missing from meshcore/platformio.ini: MeshCore changed its build layout")
        lines.append(f"[{sec}]")
        for key, val in cp.items(sec):
            if key in REWRITE:
                val = REWRITE[key](val)
            val = "\n".join("  " + l.strip() if i else l.strip() for i, l in enumerate(val.strip().split("\n")) if l.strip())
            lines.append(f"{key} = {val}")
        lines.append("")
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        # the version comment may differ (describe output) without the settings changing
        strip = lambda t: "\n".join(l for l in t.splitlines() if not l.startswith("; MeshCore version"))
        if strip(current) != strip(text):
            print("meshcore_base.ini is out of date: run  python3 tools/sync_meshcore_base.py")
            sys.exit(1)
        print("meshcore_base.ini is up to date")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
