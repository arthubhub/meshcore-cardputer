# PlatformIO extra script (pre:) of the SQLite trial env: embeds docs/storage/schema.sql in the firmware, so the device
# tests the very schema that is documented. Writes $BUILD_DIR/generated/DbSchema.inc only when it changes (".inc", not
# ".h": see pio_version.py about project.checksum).
import os

Import("env")  # noqa: F821 (provided by PlatformIO/SCons)

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
SCHEMA = os.path.join(PROJECT_DIR, "docs", "storage", "schema.sql")
DELIM = "cpadvsql"


def generate():
    with open(SCHEMA, encoding="utf-8") as f:
        sql = f.read()
    if ")" + DELIM + '"' in sql:
        raise SystemExit(f"{SCHEMA} contains the raw string delimiter")
    out = (f"// Generated by tools/pio_dbschema.py from docs/storage/schema.sql - do not edit\n"
           f'static const char DB_SCHEMA[] = R"{DELIM}(\n{sql}){DELIM}";\n')
    gen = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    os.makedirs(gen, exist_ok=True)
    path = os.path.join(gen, "DbSchema.inc")
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != out:
        with open(path, "w", encoding="utf-8") as f:
            f.write(out)
        print(f"[cpadv-dbschema] {path} written ({len(sql)} bytes of SQL)")
    env.Append(CPPPATH=[gen])  # noqa: F821


generate()
