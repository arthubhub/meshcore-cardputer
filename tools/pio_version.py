# PlatformIO extra script (pre:) for every Cardputer env - firmware version and build date (RELEASE-7).
#
#  1. Writes $BUILD_DIR/generated/CpadvVersion.inc (CPADV_VERSION, CPADV_MESHCORE_VERSION), only when the
#     content changes: a new version recompiles the few files that include it, not the whole firmware.
#     Not ".h" on purpose: with src_dir = . PlatformIO hashes the list of every .c/.cpp/.h file under the
#     project (.pio included) and wipes .pio/build when that list changes (project.checksum).
#  2. After linking, before esptool turns the ELF into firmware.bin, writes our version, the env name and the
#     real build date into the ESP-IDF app descriptor (.flash.appdesc). The prebuilt Arduino framework ships
#     its own ("esp-idf: v4.4.7", "Mar  5 2024"); the descriptor is what the other dual-boot slot, esptool
#     image_info and OTA tools read. esptool computes the image checksum and hash afterwards.
#
# Version rules: tools/version.py. Per-env suffix: custom_cpadv_version_suffix (e.g. -demo).
import os
import struct
import sys
import time

Import("env")  # noqa: F821 (provided by PlatformIO/SCons)

PROJECT_DIR = env.subst("$PROJECT_DIR")  # noqa: F821
sys.path.insert(0, os.path.join(PROJECT_DIR, "tools"))
import version  # noqa: E402

PIOENV = env.subst("$PIOENV")  # noqa: F821
SUFFIX = env.GetProjectOption("custom_cpadv_version_suffix", "").strip()  # noqa: F821
VERSION = version.describe(PROJECT_DIR) + SUFFIX
MESHCORE = version.meshcore_version(PROJECT_DIR)

APPDESC_MAGIC = 0xABCD5432
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def log(msg):
    print(f"[cpadv-version] {PIOENV}: {msg}")


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_header():
    gen = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
    os.makedirs(gen, exist_ok=True)
    path = os.path.join(gen, "CpadvVersion.inc")
    text = ("#pragma once\n"
            "// GENERATED by tools/pio_version.py at build time - do not edit.\n"
            f"#define CPADV_VERSION {c_string(VERSION)}\n"
            f"#define CPADV_MESHCORE_VERSION {c_string(MESHCORE)}\n")
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)
    env.Append(CPPPATH=[gen])  # noqa: F821


def find_section(elf, name):
    """(file offset, size) of an ELF32 little-endian section, or None."""
    if elf[:4] != b"\x7fELF" or elf[4] != 1 or elf[5] != 1:
        return None
    shoff, = struct.unpack_from("<I", elf, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x2E)
    def header(i):
        return struct.unpack_from("<IIIIII", elf, shoff + i * shentsize)   # name type flags addr offset size
    strtab_off = header(shstrndx)[4]
    for i in range(shnum):
        name_off, _, _, _, off, size = header(i)
        end = elf.index(b"\0", strtab_off + name_off)
        if elf[strtab_off + name_off:end].decode(errors="replace") == name:
            return off, size
    return None


def put(buf, off, size, text):
    data = text.encode()[:size - 1]
    buf[off:off + size] = data + b"\0" * (size - len(data))


def patch_appdesc(target, source, env):
    path = source[0].get_abspath()
    with open(path, "rb") as f:
        elf = bytearray(f.read())
    sec = find_section(elf, ".flash.appdesc")
    if not sec or sec[1] < 112:
        log("WARNING: no .flash.appdesc section, app descriptor left as is")
        return
    off = sec[0]
    if struct.unpack_from("<I", elf, off)[0] != APPDESC_MAGIC:
        log("WARNING: app descriptor magic not found, left as is")
        return
    t = time.localtime()
    put(elf, off + 16, 32, VERSION)                                           # version
    put(elf, off + 48, 32, PIOENV)                                            # project_name
    put(elf, off + 80, 16, time.strftime("%H:%M:%S", t))                      # time
    put(elf, off + 96, 16, f"{MONTHS[t.tm_mon - 1]} {t.tm_mday:2d} {t.tm_year}")   # date, like __DATE__
    with open(path, "wb") as f:
        f.write(elf)
    log(f"app descriptor set: {VERSION}, {PIOENV}")


write_header()
env.AddPreAction("$BUILD_DIR/${PROGNAME}.bin", patch_appdesc)  # noqa: F821
log(f"{VERSION} (MeshCore {MESHCORE})")
