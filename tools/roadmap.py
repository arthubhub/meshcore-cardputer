#!/usr/bin/env python3
"""Roadmap of the project: docs/roadmap.json is the source of truth, docs/ROADMAP.md is generated.

    python3 tools/roadmap.py                         # validate the JSON, rewrite docs/ROADMAP.md
    python3 tools/roadmap.py --check                 # exit 1 if the JSON is invalid or ROADMAP.md is stale (CI)
    python3 tools/roadmap.py --release-summary [--since <git ref>]
                                                     # Markdown block for the release notes (stdout)

Workflow: edit docs/roadmap.json (move an item by changing its "status", add items with the next free
number of their category), run this script, commit both files together. Standard library only.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, "docs", "roadmap.json")
MD_PATH = os.path.join(ROOT, "docs", "ROADMAP.md")
REPO_URL = "https://github.com/arthubhub/meshcore-cardputer"
ID_RE = re.compile(r"^([A-Z]+)-([1-9][0-9]*)$")


def load(text=None):
    if text is None:
        with open(JSON_PATH, encoding="utf-8") as f:
            text = f.read()
    return json.loads(text)


def validate(doc):
    errors = []
    prefixes = {c["prefix"]: c["name"] for c in doc["categories"]}
    statuses = {s["key"] for s in doc["statuses"]}
    sizes = set(doc["sizes"])
    ids = set()
    for item in doc["items"]:
        where = item.get("id", "?")
        m = ID_RE.match(item.get("id", ""))
        if not m:
            errors.append(f"{where}: id must look like CATEGORY-<number> in full words (e.g. RADIO-3)")
            continue
        if item["id"] in ids:
            errors.append(f"{where}: duplicate id")
        ids.add(item["id"])
        if m.group(1) not in prefixes:
            errors.append(f"{where}: unknown prefix {m.group(1)} (known: {', '.join(prefixes)})")
        elif prefixes[m.group(1)] != item.get("category"):
            errors.append(f"{where}: prefix {m.group(1)} belongs to category '{prefixes[m.group(1)]}', "
                          f"not '{item.get('category')}'")
        if item.get("status") not in statuses:
            errors.append(f"{where}: status must be one of {', '.join(sorted(statuses))}")
        if item.get("priority") not in (0, 1, 2, 3):
            errors.append(f"{where}: priority must be 0..3")
        if item.get("size") not in sizes:
            errors.append(f"{where}: size must be one of {', '.join(sizes)}")
        for key in ("title", "details"):
            if not str(item.get(key, "")).strip():
                errors.append(f"{where}: empty {key}")
    for item in doc["items"]:
        for dep in item.get("depends_on", []):
            if dep not in ids:
                errors.append(f"{item['id']}: depends on unknown item {dep}")
            if dep == item["id"]:
                errors.append(f"{item['id']}: depends on itself")
    return errors


def sort_key(item):
    prefix, num = ID_RE.match(item["id"]).groups()
    return (item["priority"], {"S": 0, "M": 1, "L": 2, "XL": 3}.get(item["size"], 9), prefix, int(num))


def status_name(doc, key):
    return {s["key"]: s["name"] for s in doc["statuses"]}[key]


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(doc):
    items = doc["items"]
    open_items = [i for i in items if i["status"] != "done"]
    out = []
    out.append(f"# {doc['title']}")
    out.append("")
    out.append("<!-- GENERATED by tools/roadmap.py from docs/roadmap.json - edit the JSON, then run the script. -->")
    out.append("")
    out.append("What the MeshCore firmware for the M5Stack Cardputer ADV + Cap LoRa-1262 could do next, feature by "
               "feature, with a priority and a size for each item. This file is generated: change "
               "[`roadmap.json`](roadmap.json), then run `python3 tools/roadmap.py`.")
    out.append("")
    out.append(f"Last updated {doc['updated']} · {len(open_items)} open items · "
               f"{sum(1 for i in items if i['status'] == 'done')} done.")
    out.append("")

    out.append("## How to read it")
    out.append("")
    out.append("- **Priority**: " + " · ".join(f"**{p[:2]}**{p[2:]}" for p in doc["priorities"]) + ".")
    out.append("- **Size** (agent-assisted development): " +
               " · ".join(f"**{k}** {v}" for k, v in doc["sizes"].items()) + ".")
    out.append("- **Status**: " + " → ".join(s["name"] for s in reversed(doc["statuses"][:-1])) + " → Done.")
    out.append("- ★ marks an idea requested by the project owner.")
    out.append("- **Branches**: work on an item happens on `feat/<ID>/base` (sub-branches `feat/<ID>/<part>`), "
               "or `fix/<ID>-<short-name>` for a small fix. See CLAUDE.md.")
    out.append("")

    out.append("## Overview")
    out.append("")
    header = ["Category"] + [s["name"] for s in doc["statuses"]]
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    for c in doc["categories"]:
        row = [c["name"]]
        for s in doc["statuses"]:
            n = sum(1 for i in items if i["category"] == c["name"] and i["status"] == s["key"])
            row.append(str(n) if n else "·")
        out.append("| " + " | ".join(row) + " |")
    out.append("")

    for key in ("in-progress", "next"):
        sel = sorted((i for i in items if i["status"] == key), key=sort_key)
        out.append(f"## {status_name(doc, key)}")
        out.append("")
        if not sel:
            out.append("_Nothing here yet._")
        for i in sel:
            out.append(f"- **[{i['id']}](#{i['id'].lower()})** {i['title']} · P{i['priority']} · {i['size']}")
        out.append("")

    out.append("## By category")
    out.append("")
    for c in doc["categories"]:
        sel = [i for i in items if i["category"] == c["name"]]
        if not sel:
            continue
        sel.sort(key=lambda i: (i["status"] == "done", int(ID_RE.match(i["id"]).group(2))))
        out.append(f"### {c['name']}")
        out.append("")
        out.append("| ID | Item | Priority | Size | Status | Depends on |")
        out.append("|---|---|---|---|---|---|")
        for i in sel:
            star = " ★" if i.get("requested") else ""
            deps = ", ".join(i.get("depends_on", [])) or "·"
            out.append(f"| [{i['id']}](#{i['id'].lower()}) | {cell(i['title'])}{star} | P{i['priority']} | "
                       f"{i['size']} | {status_name(doc, i['status'])} | {deps} |")
        out.append("")
        for i in sel:
            star = " ★" if i.get("requested") else ""
            out.append(f"#### {i['id']}")
            out.append("")
            out.append(f"**{i['title']}**{star} · P{i['priority']} · {i['size']} · {status_name(doc, i['status'])}"
                       + (f" · after {', '.join(i['depends_on'])}" if i.get("depends_on") else ""))
            out.append("")
            out.append(i["details"])
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def doc_at(ref):
    """roadmap.json as it was at a git ref, or None."""
    try:
        text = subprocess.check_output(["git", "-C", ROOT, "show", f"{ref}:docs/roadmap.json"],
                                       stderr=subprocess.DEVNULL, text=True)
        return load(text)
    except Exception:
        return None


def release_summary(doc, since=None):
    items = doc["items"]
    link = f"{REPO_URL}/blob/main/docs/ROADMAP.md"
    out = ["## Roadmap", ""]
    done_ids = {i["id"] for i in items if i["status"] == "done"}
    if since:
        before = doc_at(since)
        if before is not None:
            was_done = {i["id"] for i in before["items"] if i["status"] == "done"}
            new_done = [i for i in items if i["id"] in done_ids - was_done]
            out.append(f"Completed since {since}:" if new_done else f"No roadmap item completed since {since}.")
            for i in new_done:
                out.append(f"- **{i['id']}** {i['title']}")
            out.append("")
    for key in ("in-progress", "next"):
        sel = sorted((i for i in items if i["status"] == key), key=sort_key)
        if sel:
            out.append(f"{status_name(doc, key)}:")
            for i in sel:
                out.append(f"- **{i['id']}** {i['title']} (P{i['priority']}, {i['size']})")
            out.append("")
    open_items = [i for i in items if i["status"] != "done"]
    by_pri = [sum(1 for i in open_items if i["priority"] == p) for p in range(4)]
    out.append(f"{len(open_items)} open items (P0 {by_pri[0]}, P1 {by_pri[1]}, P2 {by_pri[2]}, P3 {by_pri[3]}), "
               f"{len(done_ids)} done. Full roadmap: [docs/ROADMAP.md]({link})")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate and verify ROADMAP.md is up to date")
    ap.add_argument("--release-summary", action="store_true", help="print a Markdown summary for release notes")
    ap.add_argument("--since", help="git ref of the previous release (with --release-summary)")
    args = ap.parse_args()

    doc = load()
    errors = validate(doc)
    if errors:
        print("docs/roadmap.json is invalid:\n  " + "\n  ".join(errors), file=sys.stderr)
        sys.exit(1)

    if args.release_summary:
        sys.stdout.write(release_summary(doc, args.since))
        return

    md = render_markdown(doc)
    if args.check:
        current = open(MD_PATH, encoding="utf-8").read() if os.path.exists(MD_PATH) else ""
        if current != md:
            print("docs/ROADMAP.md is out of date: run  python3 tools/roadmap.py", file=sys.stderr)
            sys.exit(1)
        print(f"roadmap OK: {len(doc['items'])} items, ROADMAP.md up to date")
        return
    with open(MD_PATH, "w", encoding="utf-8") as f:
        f.write(md)
    print(f"written {os.path.relpath(MD_PATH, ROOT)} ({len(doc['items'])} items)")


if __name__ == "__main__":
    main()
